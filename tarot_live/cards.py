@dataclass(frozen=True)
class Card:
    id: int
    name_th: str
    name_en: str
    upright: str
    reversed: str


def _build() -> list[Card]:
    deck: list[Card] = []
    for th, en, up, rev in MAJOR:
        deck.append(Card(len(deck), th, en, up, rev))
    for s_th, s_en, s_theme in SUITS:
        for r_th, r_en, up, rev in RANKS:
            deck.append(Card(
                len(deck), f"{r_th}{s_th}", f"{r_en} of {s_en}",
                f"{up} ({s_theme})", f"{rev} ({s_theme})",
            ))
    return deck


DECK: list[Card] = _build()
assert len(DECK) == 78


@dataclass(frozen=True)
class Drawn:
    card: Card
    is_reversed: bool

    @property
    def meaning(self) -> str:
        return self.card.reversed if self.is_reversed else self.card.upright

    @property
    def label(self) -> str:
        return f"{self.card.name_th} ({'กลับหัว' if self.is_reversed else 'ตั้งตรง'})"

    def to_dict(self) -> dict:
        return {
            "id": self.card.id, "name_th": self.card.name_th, "name_en": self.card.name_en,
            "reversed": self.is_reversed, "meaning": self.meaning,
        }


def draw(n: int, rng: random.Random | None = None) -> list[Drawn]:
    """Draw n distinct cards, each independently upright or reversed."""
    rng = rng or random
    n = max(1, min(n, len(DECK)))
    return [Drawn(c, rng.random() < 0.3) for c in rng.sample(DECK, n)]
